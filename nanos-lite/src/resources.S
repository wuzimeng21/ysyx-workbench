# ============================================================
# 使用场景（Nanos-lite / Navy 中的应用）
# ============================================================

# 1. ramdisk.img 的嵌入:
#    - 在 PA3/PA4 中，ramdisk 包含了所有用户程序
#    - 操作系统启动时，直接从内存中的 ramdisk_start 读取程序
#    - 不需要真实的磁盘设备

# 2. logo 的嵌入:
#    - 开机时显示 ASCII 艺术字或版权信息
#    - 例如: nanos-lite 启动时显示的 "Nanos-lite" logo

# 3. 其他资源的嵌入:
#    - 字体文件 (.fnt, .ttf)
#    - 图像数据 (.bmp, .png)
#    - 音频数据 (.wav, .ogg)
#    - 配置文件 (.cfg, .json)


# ============================================================
# 编译和链接过程
# ============================================================

# 1. 编译阶段:
#    gcc -c -o file.o file.S
#    # 将 .S 汇编文件编译成目标文件
#    # .incbin 指令在此阶段执行：将文件内容嵌入到 .o 文件中

# 2. 链接阶段:
#    ld -T linker.ld -o program file.o ...
#    # 链接器根据链接脚本安排各个段的内存位置
#    # 全局符号（.global）可以被其他目标文件引用

# 3. 运行时:
#    - ramdisk_start 和 ramdisk_end 是确定的地址
#    - 可以直接通过指针访问这些数据
#    - 数据在程序加载时就已经存在于内存中