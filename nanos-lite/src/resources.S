# ============================================================
# 汇编指令解释
# ============================================================

# .section .data
# 作用: 指定后续代码放在 .data 节（数据段）
# 特点: 
#   - 可读可写
#   - 程序运行时会被加载到内存
#   - 用于存放已初始化的全局变量
.section .data

# .global ramdisk_start, ramdisk_end
# 作用: 声明这两个符号为全局可见
# 效果:
#   - 链接器可以看到这些符号
#   - C/C++ 代码可以通过 extern 声明来引用它们
# 示例: extern char ramdisk_start[];  // 在 C 代码中使用
.global ramdisk_start, ramdisk_end

# ramdisk_start:
# 作用: 定义一个标签（符号），标记当前位置的地址
# 等价于 C 语言中的: char ramdisk_start[] = { ... };
ramdisk_start:

# .incbin "build/ramdisk.img"
# 作用: 将指定二进制文件的内容原样嵌入到当前汇编文件中
# 细节:
#   - 不进行任何解析或修改，直接复制字节
#   - "build/ramdisk.img" 是文件路径（相对于编译目录）
#   - 通常用于嵌入固件、字体、图像、ramdisk 等二进制资源
.incbin "build/ramdisk.img"

# ramdisk_end:
# 作用: 标记 ramdisk 的结束位置
# 使用: ramdisk_end - ramdisk_start 可以得到 ramdisk 的大小
ramdisk_end:


# ============================================================
# 第二个段: 只读数据段
# ============================================================

# .section .rodata
# 作用: 放在只读数据段
# 特点:
#   - 只读，不可修改
#   - 程序运行时通常放在只读内存区域（如 ROM 或受保护的内存页）
#   - 尝试写入会导致 Segmentation Fault
.section .rodata

# .globl logo
# 作用: 声明 logo 符号为全局可见
# 用途: 让 C 代码可以访问 logo 的内容
.globl logo

# logo:
# 作用: 定义一个标签，指向 logo 数据的起始位置
logo:

# .incbin "resources/logo.txt"
# 作用: 嵌入文本文件的内容
# 注意: 
#   - 这里嵌入的是文本文件，不是二进制文件
#   - 文本文件中的字符（包括换行符）会被原样嵌入
.incbin "resources/logo.txt"

# .byte 0
# 作用: 在文件末尾添加一个零字节（字符串结束符）
# 原因:
#   - logo.txt 文件本身可能没有末尾的 '\0'
#   - 添加这个字节后，C 代码可以将 logo 当作字符串处理
#   - 例如: printf("%s", logo);  // 安全地打印
.byte 0


# ============================================================
# 生成的符号表（在 C 代码中的使用方式）
# ============================================================

# 1. 访问 ramdisk:
#    extern char ramdisk_start[];
#    extern char ramdisk_end[];
#    
#    size_t ramdisk_size = ramdisk_end - ramdisk_start;
#    // ramdisk_size 就是嵌入的 ramdisk 文件大小
#    
#    // 读取 ramdisk 数据
#    for (size_t i = 0; i < ramdisk_size; i++) {
#        putchar(ramdisk_start[i]);
#    }

# 2. 访问 logo:
#    extern char logo[];
#    
#    // logo 自动以 '\0' 结尾，可以直接当作字符串使用
#    printf("%s", logo);
#    
#    // 或者在图形界面中绘制 logo
#    draw_text(logo, x, y, color);


